CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(190) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(16) NOT NULL DEFAULT 'student'
        CHECK (role IN ('student', 'lecturer', 'maintenance', 'admin')),
    oidc_sub VARCHAR(255) UNIQUE,
    email_verified_at TIMESTAMP,
    session_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMP;
ALTER TABLE users ADD COLUMN IF NOT EXISTS session_version INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS auth_tokens (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    purpose VARCHAR(24) NOT NULL CHECK (purpose IN ('verify_email', 'password_reset')),
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_auth_token_user_purpose UNIQUE (user_id, purpose)
);

CREATE TABLE IF NOT EXISTS campus_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building VARCHAR(100) NOT NULL,
    room VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_campus_location UNIQUE (building, room)
);

CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference_code VARCHAR(24) NOT NULL UNIQUE,
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    title VARCHAR(160) NOT NULL,
    category VARCHAR(60) NOT NULL,
    location VARCHAR(190) NOT NULL,
    location_id BIGINT REFERENCES campus_locations(id) ON DELETE SET NULL,
    urgency VARCHAR(16) NOT NULL DEFAULT 'Normal'
        CHECK (urgency IN ('Low', 'Normal', 'High', 'Urgent')),
    description TEXT NOT NULL,
    photo_name VARCHAR(255),
    is_anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(16) NOT NULL DEFAULT 'Submitted'
        CHECK (status IN ('Submitted', 'Assigned', 'In progress', 'Resolved')),
    assigned_to BIGINT REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS report_updates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    actor_id BIGINT REFERENCES users(id),
    status VARCHAR(32) NOT NULL,
    note VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS maintenance_work_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    labor_minutes SMALLINT NOT NULL CHECK (labor_minutes >= 0),
    parts_used VARCHAR(500),
    note VARCHAR(500) NOT NULL,
    follow_up_at DATE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL UNIQUE REFERENCES reports(id) ON DELETE CASCADE,
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    note VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS app_settings (
    setting_key VARCHAR(60) PRIMARY KEY,
    setting_value VARCHAR(20) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auth_attempts (
    bucket_hash CHAR(64) PRIMARY KEY,
    window_started_at TIMESTAMP NOT NULL,
    attempts SMALLINT NOT NULL CHECK (attempts >= 0)
);

CREATE INDEX IF NOT EXISTS idx_campus_locations_active
    ON campus_locations (is_active, building, room);
CREATE INDEX IF NOT EXISTS idx_reports_status_created
    ON reports (status, created_at);
CREATE INDEX IF NOT EXISTS idx_reports_created
    ON reports (created_at);
CREATE INDEX IF NOT EXISTS idx_reports_reporter_created
    ON reports (reporter_id, created_at);
CREATE INDEX IF NOT EXISTS idx_reports_location_created
    ON reports (location_id, created_at);
CREATE INDEX IF NOT EXISTS idx_updates_report_created
    ON report_updates (report_id, created_at);
CREATE INDEX IF NOT EXISTS idx_work_logs_report_created
    ON maintenance_work_logs (report_id, created_at);
CREATE INDEX IF NOT EXISTS idx_auth_attempts_window
    ON auth_attempts (window_started_at);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_expires
    ON auth_tokens (expires_at);

